import { expect } from "@playwright/test";
import { randomUUID } from "node:crypto";
import { test, fixtureData, login, mutate, activate } from "./fixtures/accounts";

test("AI 使用区分调用与采纳，披露历史和冲突保留草稿", async ({ page, accounts }, testInfo) => {
  await page.goto("/"); await login(page, accounts.owner, accounts.password);
  await page.getByRole("button", { name: "创建项目" }).click();
  await page.getByLabel("项目名称", { exact: true }).fill("披露验收");
  await page.getByRole("button", { name: "创建", exact: true }).click();
  const panel = page.getByRole("region", { name: "AI 使用与披露", exact: true });
  await activate(page, 'AI 使用与披露');
  await expect(panel.getByLabel("AI 使用说明", { exact: true })).toHaveValue(/暂无系统内模型任务记录/);
  const project = (await (await page.request.get("/api/v1/projects/")).json()).results[0];
  const projectPath = `projects/${project.id}/`;
  expect((await mutate(page.request, projectPath + "policies/", "POST", { version: project.version, source: "自制规则", source_version: "v1", notes: "", verified: true, allowed_actions: ["expression"] })).status()).toBe(201);
  const draft = { version: 0, request_key: randomUUID(), research: { question: "", method: "", result: "" }, blocks: [{ id: randomUUID(), text: "方法", heading_level: 1 }, { id: randomUUID(), text: "本研究对样本进行了观察。", heading_level: 0 }] };
  expect((await mutate(page.request, projectPath + "manuscript/", "PUT", draft)).status()).toBe(200);
  const created = JSON.parse(fixtureData("expression", accounts.prefix, { payload: { idempotency_key: randomUUID(), policy_version: 2, manuscript_version: 1, block_ids: draft.blocks.map(block => block.id), version_ids: [] } }));
  await panel.getByRole("button", { name: "刷新使用记录", exact: true }).click();
  await expect(panel).toContainText("发起模型调用 2 次 · 表达建议 1 条 · 实际采纳 0 条");
  const task = await (await page.request.get(`/api/v1/${projectPath}jobs/${created.task.id}/`)).json();
  const suggestion = task.output.suggestion_ids[0];
  expect((await mutate(page.request, projectPath + `suggestions/${suggestion}/decision/`, "POST", { request_key: randomUUID(), manuscript_version: 1, policy_version: 2, action: "accepted", meaning_confirmed: true })).status()).toBe(200);
  await panel.getByRole("button", { name: "刷新使用记录", exact: true }).click();
  await expect(panel).toContainText("实际采纳 1 条");
  await panel.getByLabel("AI 使用说明", { exact: true }).fill("作者核对：仅采纳一次表达修改。");
  await panel.getByRole("button", { name: "补充外部使用" }).click();
  await panel.getByLabel("工具与版本", { exact: true }).fill("自报工具 v1");
  await panel.getByLabel("用途", { exact: true }).fill("检查标点");
  await panel.getByLabel("使用范围或稿件位置", { exact: true }).fill("方法第 1 段");
  await panel.getByLabel("实际采纳与备注", { exact: true }).fill("未采纳外部建议");
  await panel.getByLabel("已核对使用记录、实际采纳和系统外补充").check();
  await panel.getByRole("button", { name: "保存披露新版本" }).click();
  await expect(panel).toContainText("已保存清单 v1 · 作者已核对");
  await panel.locator(".n-collapse-item__header-main").filter({ hasText: "逐项回查使用记录" }).click();
  await panel.getByRole("button", { name: "查看使用详情", exact: true }).click();
  await expect(panel).toContainText("执行器 pi-1.5.0");
  await expect(panel).toContainText("原稿 v1 的块 1、2");
  await panel.getByRole("button", { name: "回查建议 1 · 已接受", exact: true }).click();
  const change = panel.getByRole("region", { name: "使用记录中的表达修改" });
  await expect(change).toContainText("作者决定：已接受");
  await expect(change.getByLabel("文字差异").locator("del").first()).toBeVisible();
  await change.getByRole("button", { name: "查看修改前稿件" }).click();
  await expect(panel.locator(".n-collapse-item__header-main").filter({ hasText: /^稿件 v1$/ })).toBeVisible();
  await change.getByRole("button", { name: "查看采纳后稿件" }).click();
  await expect(panel.locator(".n-collapse-item__header-main").filter({ hasText: /^稿件 v2$/ })).toBeVisible();
  await panel.getByLabel("AI 使用说明", { exact: true }).fill("当前窗口的披露草稿");
  await expect(panel.getByLabel("已核对使用记录、实际采纳和系统外补充")).not.toBeChecked();
  expect((await mutate(page.request, projectPath + "manuscript/", "PUT", { ...draft, version: 2, request_key: randomUUID(), blocks: draft.blocks.map(block => ({ ...block, text: "作者自行修订的新稿。" })) })).status()).toBe(200);
  await panel.getByRole("button", { name: "保存披露新版本" }).click();
  await expect(panel.getByRole("alert")).toContainText("使用记录或稿件已有变化");
  await expect(panel.getByLabel("AI 使用说明", { exact: true })).toHaveValue("当前窗口的披露草稿");
  await panel.getByRole("button", { name: "刷新使用记录", exact: true }).click();
  await expect(panel.getByLabel("已核对使用记录、实际采纳和系统外补充")).not.toBeChecked();
  await expect(panel).toContainText("记录或稿件已变化，需重新核对");
  await panel.getByRole("button", { name: "保存披露新版本" }).click();
  await expect(panel).toContainText("已保存清单 v2 · 待作者核对");
  await panel.locator(".n-collapse-item__header-main").filter({ hasText: "披露修改历史" }).click();
  await panel.getByRole("button", { name: "清单 v1 · 当时已核对", exact: true }).click();
  await expect(panel.getByRole("article", { name: "披露历史版本" })).toContainText("作者核对：仅采纳一次表达修改。");
  await expect(panel.getByRole("article", { name: "披露历史版本" })).toContainText("自报工具 v1");
  await panel.getByLabel("AI 使用说明", { exact: true }).fill("不覆盖另一窗口的新版本");
  const state = await (await page.request.get(`/api/v1/${projectPath}disclosure/`)).json();
  expect((await mutate(page.request, projectPath + "disclosure/", "POST", { version: 2, request_key: randomUUID(), facts_token: state.facts_token, text: "另一窗口保存", external_uses: [], verified: false })).status()).toBe(201);
  await panel.getByRole("button", { name: "保存披露新版本" }).click();
  await expect(panel.getByRole("alert")).toContainText("披露清单已有新版本");
  await panel.getByRole("button", { name: "刷新使用记录", exact: true }).click();
  await expect(panel.getByRole("button", { name: "保存披露新版本" })).toBeDisabled();
  await expect(panel.getByLabel("AI 使用说明", { exact: true })).toHaveValue("不覆盖另一窗口的新版本");
  await panel.getByRole("button", { name: "保留草稿并更新保存基准" }).click();
  await panel.getByRole("button", { name: "保存披露新版本" }).click();
  await expect(panel).toContainText("已保存清单 v4");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await panel.locator("form").first().screenshot({ path: testInfo.outputPath("disclosure-editor.png") });
  const currentProject = await (await page.request.get(`/api/v1/${projectPath}`)).json();
  expect((await mutate(page.request, projectPath + "members/", "POST", { version: currentProject.version, username: accounts.reviewer, role: "reviewer" })).status()).toBe(200);
  await page.getByRole("button", { name: "退出", exact: true }).click();
  await login(page, accounts.reviewer, accounts.password);
  await page.getByRole("button", { name: /披露验收.*审阅者/ }).click();
  await activate(page, "AI 使用与披露");
  await expect(panel.getByLabel("AI 使用说明", { exact: true })).toHaveValue("不覆盖另一窗口的新版本");
  await expect(panel.getByLabel("AI 使用说明", { exact: true })).toBeDisabled();
  await expect(panel.getByRole("button", { name: "保存披露新版本" })).toHaveCount(0);
});
